    /// <summary>Monta uma questão. <paramref name="corretas"/> usa as letras das alternativas (ex.: "b" ou "ac").</summary>
    private static Questao Q(
        string id, string dominio, string topico, int nivel, string enunciado,
        string[] alternativas, string corretas, string explicacao, string[] porque, string referencia)
    {
        var ids = alternativas.Select((_, i) => ((char)('a' + i)).ToString()).ToArray();
        var certas = corretas.Select(c => c.ToString()).ToHashSet();
        var incorretas = ids.Where(i => !certas.Contains(i)).ToList();
        if (incorretas.Count != porque.Length)
            throw new InvalidOperationException($"Questão {id}: {incorretas.Count} incorretas e {porque.Length} justificativas.");
        return new Questao(
            id, dominio, topico, nivel, enunciado,
            ids.Select((x, i) => new Alternativa(x, alternativas[i])).ToList(),
            certas,
            new Explicacao(explicacao, incorretas.Select((x, i) => new ExplicacaoIncorreta(x, porque[i])).ToList(), referencia));
    }

